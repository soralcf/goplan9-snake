#include "textflag.h"

// state+0(FP) ret+8(FP)
TEXT ·Xorshift64(SB), NOSPLIT, $0-16
	MOVD state+0(FP), R0
	LSL  $13, R0, R1
	EOR  R1, R0
	LSR  $7, R0, R1
	EOR  R1, R0
	LSL  $17, R0, R1
	EOR  R1, R0
	MOVD R0, ret+8(FP)
	RET

// [优化建议]
// - 当前写法每段移位是两条指令（LSL/LSR 到 R1，再 EOR 回 R0），三点各一组，
//   共 6 条数据指令、6 级串行依赖。
// - 可选优化（移位操作数形式）：ARM64 的 EOR 属于 shifted register 指令，
//   移位直接写在源操作数里，一条指令完成“移位 + 异或”：
//	MOVD state+0(FP), R0
//	EOR  R0<<13, R0
//	EOR  R0>>7, R0
//	EOR  R0<<17, R0
//	MOVD R0, ret+8(FP)
//   数据指令 6 -> 3、依赖 6 -> 3 级。注意 Go 汇编里 `>>` 是逻辑右移（LSR），
//   算术右移才是 `->`（ASR）；这里必须是 `>>`，写成 `->` 会破坏契约。
//   收益（Apple M4，临时包，2,000,000 次连调，含 ABI0 调用/出入栈开销）：
//	当前写法   约 3.75-4.30 ns/op
//	移位操作数 约 2.84-3.00 ns/op   // 约 1.3 倍
//   风险：只需改寄存器操作数写法，契约、零状态语义、返回值位置都不变；
//   验证：跑现有 TestXorshift64 / Zero / Sequence / Random 全绿，再 objdump
//   确认函数体只剩 3 条 EOR（机器码 ca003400、ca401c00、ca004400）。
// - 不建议的优化：一次调用生成一批值来摊薄调用开销。当前每次吃食物只需 1 个
//   状态，M3 的瓶颈是渲染和终端 I/O；批量接口会让“状态由调用者维护”的契约
//   变复杂，等真有性能数据再说。
// - 小处：函数无栈帧、无调用，NOSPLIT 下 R0/R1 可以随便用，不需要保存；
//   若以后在函数里 CALL 别的汇编函数，R0/R1 属于调用者保存，那时才需要另存。
